  <h1 style="margin:0 0 8px;font-size:clamp(1.6rem,3vw,2.1rem)">Eliminación de datos personales</h1>
  <p class="text-muted small">Última revisión: 23 de octubre de 2026</p>

  <p>Podés solicitar acceso, rectificación, actualización o supresión de los datos personales asociados a tu cuenta, compra o consulta, de acuerdo con la Ley 25.326 y las demás normas aplicables.</p>

  <h2 class="h4 mt-4">Cómo realizar una solicitud</h2>
  <p>Escribí a <a href="mailto:perfushoppingbv@gmail.com"><strong>perfushoppingbv@gmail.com</strong></a> con el asunto <strong>Solicitud de datos personales — Perfushopping</strong>. Para consultas generales también está disponible <a href="mailto:clientes@perfushopping.com.ar">clientes@perfushopping.com.ar</a>.</p>

  <h2 class="h4 mt-4">Qué incluir</h2>
  <ul>
    <li>Tu nombre y apellido.</li>
    <li>El correo, teléfono o nombre de usuario que usaste para comunicarte o comprar.</li>
    <li>El canal relacionado con la solicitud: sitio web, WhatsApp, Instagram, Facebook o correo electrónico.</li>
    <li>Qué necesitás: acceso, rectificación, actualización o eliminación.</li>
  </ul>
  <p>No envíes contraseñas ni documentación sensible en el primer mensaje. Si hace falta verificar tu identidad, te indicaremos qué información mínima necesitamos y por qué.</p>

  <h2 class="h4 mt-4">Qué hacemos al recibirla</h2>
  <ol>
    <li>Verificamos que la solicitud corresponda a la persona titular o a quien esté legalmente autorizado.</li>
    <li>Localizamos los datos relacionados con la identidad o los contactos que nos indiques.</li>
    <li>Rectificamos, actualizamos, suprimimos o limitamos su tratamiento cuando corresponda.</li>
    <li>Te comunicamos el resultado por un canal de contacto razonable.</li>
  </ol>
  <p>El tratamiento de solicitudes se realiza manualmente por personal autorizado; no hay una herramienta pública de eliminación automática. Los datos incluidos en comprobantes, operaciones u otros registros sujetos a conservación legal podrían mantenerse durante el plazo que establezca la norma correspondiente.</p>

  <h2 class="h4 mt-4">Plazos y excepciones</h2>
  <p>La Ley 25.326 establece 10 días corridos para responder un pedido de acceso y 5 días hábiles para rectificar, actualizar o suprimir datos, sujeto a las excepciones legales. La supresión no procede cuando perjudique derechos legítimos de terceros o exista una obligación legal de conservación.</p>

  <h2 class="h4 mt-4">Datos tratados mediante plataformas de Meta</h2>
  <p>Si tu solicitud se refiere a mensajes recibidos por WhatsApp, Instagram o Facebook, indicá el canal y el número, perfil o identificador con el que te comunicaste. Para la información que Meta trate directamente en sus propios servicios, también podés utilizar los controles de privacidad que Meta pone a disposición de sus usuarios.</p>

  <h2 class="h4 mt-4">Conservación de conversaciones comerciales</h2>
  <p>Perfushopping propone conservar las conversaciones registradas en sistemaPS hasta 12 meses desde la última interacción del cliente, sujeto a validación legal y técnica e implementación efectiva antes de presentarse como criterio operativo vigente. El sistema todavía no automatiza esa depuración. El plazo no se aplica automáticamente a pedidos, facturas, comprobantes, reclamos, relaciones vigentes ni datos sujetos a obligaciones legales o a una causa legítima de conservación.</p>

  <p>Consultá también nuestra <a href="/politica-de-privacidad">Política de privacidad</a> o la información sobre derechos publicada por la <a href="https://www.argentina.gob.ar/aaip/datospersonales/derechos" target="_blank" rel="noopener noreferrer">AAIP</a>.</p>
